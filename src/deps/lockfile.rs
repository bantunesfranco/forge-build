//! `project.lock`: the commit every git dependency is pinned to (spec 2, 10.2).

use std::{collections::BTreeMap, io, path::Path};

use crate::config::ConfigError;

pub const LOCK_FILE: &str = "project.lock";

const HEADER: &str = "# Generated by forge. Commit this file.";

/// One pinned git dependency: what the manifest asked for (`git`, `rev`) and
/// the commit that was resolved from it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockEntry {
    pub git: String,
    pub rev: String,
    pub commit: String,
}

/// The lockfile, by dependency name.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct Lockfile {
    pub entries: BTreeMap<String, LockEntry>,
}

impl Lockfile {
    /// Reads `path`; a missing file is an empty lockfile.
    pub fn load(path: &Path) -> Result<Lockfile, ConfigError> {
        let text = match std::fs::read_to_string(path) {
            Ok(text) => text,
            Err(e) if e.kind() == io::ErrorKind::NotFound => return Ok(Lockfile::default()),
            Err(source) => {
                return Err(ConfigError::Io {
                    path: path.into(),
                    source,
                });
            }
        };
        let table: toml::Table = toml::from_str(&text).map_err(|source| ConfigError::Parse {
            path: path.into(),
            source,
        })?;
        let field = path.display().to_string();
        let bad = |message: String| ConfigError::invalid(field.clone(), message);

        let mut entries = BTreeMap::new();
        let mut version = None;
        for (key, value) in &table {
            match (key.as_str(), value) {
                ("version", toml::Value::Integer(v)) => version = Some(*v),
                ("version", _) => return Err(bad("`version` must be an integer".into())),
                ("dependency", toml::Value::Table(deps)) => {
                    for (name, entry) in deps {
                        let toml::Value::Table(entry) = entry else {
                            return Err(bad(format!("`dependency.{name}` must be a table")));
                        };
                        entries.insert(name.clone(), parse_entry(name, entry, &bad)?);
                    }
                }
                (other, _) => return Err(bad(format!("unknown key `{other}`"))),
            }
        }
        match version {
            Some(1) => Ok(Lockfile { entries }),
            Some(v) => Err(bad(format!(
                "unsupported lockfile version {v}; this forge reads version 1"
            ))),
            None => Err(bad("missing `version`".into())),
        }
    }

    /// The file's text. The same entries always give the same text.
    pub fn render(&self) -> String {
        let mut out = format!("{HEADER}\nversion = 1\n");
        for (name, e) in &self.entries {
            out.push_str(&format!(
                "\n[dependency.{}]\ngit = {}\nrev = {}\ncommit = {}\n",
                key(name),
                string(&e.git),
                string(&e.rev),
                string(&e.commit)
            ));
        }
        out
    }

    pub fn save(&self, path: &Path) -> io::Result<()> {
        std::fs::write(path, self.render())
    }
}

fn parse_entry(
    name: &str,
    table: &toml::Table,
    bad: &dyn Fn(String) -> ConfigError,
) -> Result<LockEntry, ConfigError> {
    let get = |k: &str| match table.get(k) {
        Some(toml::Value::String(s)) => Ok(s.clone()),
        Some(_) => Err(bad(format!("`dependency.{name}.{k}` must be a string"))),
        None => Err(bad(format!("`dependency.{name}` has no `{k}`"))),
    };
    if let Some(unknown) = table
        .keys()
        .find(|k| !matches!(k.as_str(), "git" | "rev" | "commit"))
    {
        return Err(bad(format!("unknown key `dependency.{name}.{unknown}`")));
    }
    Ok(LockEntry {
        git: get("git")?,
        rev: get("rev")?,
        commit: get("commit")?,
    })
}

fn string(s: &str) -> String {
    toml::Value::String(s.to_string()).to_string()
}

/// A table-header key: bare when TOML allows it, quoted otherwise.
fn key(name: &str) -> String {
    let bare = !name.is_empty()
        && name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'-');
    if bare { name.to_string() } else { string(name) }
}
