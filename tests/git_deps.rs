//! Git dependencies pinned through `project.lock`, and `forge update`
//! (spec 10.2, 11 step 7). Every repository here is a local fixture; nothing
//! touches the network.
mod common;

use std::{
    fs,
    path::{Path, PathBuf},
    process::Command,
};

use common::{Fixture, compile_args_of};
use forge_build::{
    config::{self, Diagnostics, Level},
    deps::{
        self,
        git::{checkout, resolve_rev},
        lockfile::{LockEntry, Lockfile},
    },
    graph::Graph,
    project::Project,
};
use tempfile::TempDir;

fn have_git() -> bool {
    Command::new("git")
        .arg("--version")
        .output()
        .is_ok_and(|o| o.status.success())
}

/// Skips a test on a machine without git.
macro_rules! need_git {
    () => {
        if !have_git() {
            eprintln!("skipped: git is not installed");
            return;
        }
    };
}

/// A local repository to depend on: two commits on `master` and an annotated
/// tag `v1` on the first one.
struct Upstream {
    dir: TempDir,
    first: String,
}

fn git_in(dir: &Path, args: &[&str]) -> String {
    let out = Command::new("git")
        .args(["-c", "commit.gpgsign=false", "-c", "tag.gpgsign=false"])
        .args(args)
        .current_dir(dir)
        .output()
        .expect("run git");
    assert!(
        out.status.success(),
        "git {args:?} failed: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    String::from_utf8_lossy(&out.stdout).trim().to_string()
}

impl Upstream {
    fn new() -> Self {
        let dir = tempfile::tempdir().unwrap();
        let repo = dir.path().join("repo");
        fs::create_dir_all(repo.join("include")).unwrap();
        git_in(&repo, &["init", "-b", "master", "."]);
        git_in(&repo, &["config", "user.email", "forge@example.com"]);
        git_in(&repo, &["config", "user.name", "Forge Test"]);
        let up = Upstream {
            dir,
            first: String::new(),
        };
        up.commit("1");
        git_in(&repo, &["tag", "-a", "v1", "-m", "v1"]);
        let first = up.head();
        up.commit("2");
        Upstream { first, ..up }
    }

    fn repo(&self) -> PathBuf {
        self.dir.path().join("repo")
    }

    /// The URL a manifest uses: the plain path with forward slashes.
    fn url(&self) -> String {
        self.repo().to_string_lossy().replace('\\', "/")
    }

    fn commit(&self, value: &str) {
        let repo = self.repo();
        fs::write(repo.join("include/dep.h"), format!("#define DEP {value}\n")).unwrap();
        git_in(&repo, &["add", "."]);
        git_in(&repo, &["commit", "-m", &format!("change {value}")]);
    }

    fn head(&self) -> String {
        git_in(&self.repo(), &["rev-parse", "HEAD"])
    }
}

fn manifest(url: &str, rev: &str) -> String {
    format!(
        concat!(
            "[workspace]\nname = \"t\"\nversion = \"1\"\nc = \"17\"\n",
            "[dependency.dep]\ngit = \"{}\"\nrev = \"{}\"\nkind = \"header-only\"\n",
            "include.public = [\"include\"]\n",
            "[bin.app]\nsources = [\"main.c\"]\ndeps = [\"dep\"]\n",
        ),
        url, rev
    )
}

fn consumer(url: &str, rev: &str) -> Fixture {
    let f = Fixture::new(&manifest(url, rev));
    f.touch("main.c");
    f
}

fn lock_of(f: &Fixture) -> Lockfile {
    Lockfile::load(&f.root.join("project.lock")).unwrap()
}

fn checkout_head(f: &Fixture) -> String {
    git_in(
        &f.root.join("build/deps/dep/source"),
        &["rev-parse", "HEAD"],
    )
}

fn infos(p: &Project) -> Vec<String> {
    p.diagnostics
        .items
        .iter()
        .filter(|(l, _)| *l == Level::Info)
        .map(|(_, m)| m.clone())
        .collect()
}

#[test]
fn lockfile_round_trip() {
    let t = tempfile::tempdir().unwrap();
    let path = t.path().join("project.lock");
    assert!(Lockfile::load(&path).unwrap().entries.is_empty());

    let mut lock = Lockfile::default();
    lock.entries.insert(
        "glm".into(),
        LockEntry {
            git: "https://github.com/g-truc/glm".into(),
            rev: "1.0.2".into(),
            commit: "a".repeat(40),
        },
    );
    lock.entries.insert(
        "stb".into(),
        LockEntry {
            git: "https://github.com/nothings/stb".into(),
            rev: "master".into(),
            commit: "b".repeat(40),
        },
    );
    lock.save(&path).unwrap();

    let text = fs::read_to_string(&path).unwrap();
    assert!(text.starts_with("# Generated by forge. Commit this file.\nversion = 1\n"));
    assert!(text.contains("[dependency.glm]\ngit = \"https://github.com/g-truc/glm\"\n"));
    assert_eq!(Lockfile::load(&path).unwrap().entries, lock.entries);
}

#[test]
fn lockfile_rejects_garbage() {
    let t = tempfile::tempdir().unwrap();
    let path = t.path().join("project.lock");
    for (text, what) in [
        ("version = 2\n", "version"),
        (
            "version = 1\n[dependency.a]\ngit = \"u\"\nrev = \"r\"\n",
            "commit",
        ),
        ("version = 1\n[other]\n", "other"),
        ("not toml [", "project.lock"),
    ] {
        fs::write(&path, text).unwrap();
        let e = Lockfile::load(&path).expect_err(text).to_string();
        assert!(e.contains(what), "{text}: {e}");
    }
}

#[test]
fn first_build_pins_and_writes_lock_with_info() {
    need_git!();
    let up = Upstream::new();
    let f = consumer(&up.url(), "master");
    let p = f.load().unwrap();

    let lock = lock_of(&f);
    let entry = &lock.entries["dep"];
    assert_eq!(entry.git, up.url());
    assert_eq!(entry.rev, "master");
    assert_eq!(entry.commit, up.head());
    let short = &entry.commit[..12];
    assert!(
        infos(&p).contains(&format!("pinned dep master -> {short}")),
        "{:?}",
        p.diagnostics
    );
    assert_eq!(checkout_head(&f), up.head());

    // The checkout is the dependency's source directory: its include dir is used.
    let g = Graph::from_project(&p).unwrap();
    let args = compile_args_of(&p, &g, "main.c");
    assert!(
        args.iter()
            .any(|a| a.contains("build/deps/dep/source/include")),
        "{args:?}"
    );
}

#[test]
fn locked_commit_is_used_even_after_branch_moves() {
    need_git!();
    let up = Upstream::new();
    let f = consumer(&up.url(), "master");
    f.load().unwrap();
    let pinned = up.head();

    up.commit("3");
    assert_ne!(up.head(), pinned);
    let p = f.load().unwrap();
    assert_eq!(checkout_head(&f), pinned);
    assert_eq!(lock_of(&f).entries["dep"].commit, pinned);
    assert!(
        infos(&p).iter().all(|m| !m.starts_with("pinned")),
        "{:?}",
        infos(&p)
    );
}

#[test]
fn update_moves_to_new_commit() {
    need_git!();
    let up = Upstream::new();
    let f = consumer(&up.url(), "master");
    f.load().unwrap();
    let old = up.head();
    up.commit("3");
    let new = up.head();

    let m = config::load(&f.manifest()).unwrap();
    let mut diags = Diagnostics::default();
    deps::update(&f.root, &m, None, &mut diags).unwrap();
    assert_eq!(lock_of(&f).entries["dep"].commit, new);
    assert!(
        diags
            .items
            .iter()
            .any(|(_, m)| m.starts_with("pinned dep master -> ")),
        "{diags:?}"
    );
    // update does not fetch: the checkout still has the old commit.
    assert_eq!(checkout_head(&f), old);

    // The next load follows the lock.
    f.load().unwrap();
    assert_eq!(checkout_head(&f), new);
}

#[test]
fn update_one_dependency_and_unknown_name() {
    need_git!();
    let up = Upstream::new();
    let f = consumer(&up.url(), "master");
    f.load().unwrap();
    up.commit("3");

    let m = config::load(&f.manifest()).unwrap();
    let mut diags = Diagnostics::default();
    let e = deps::update(&f.root, &m, Some("nope"), &mut diags)
        .unwrap_err()
        .to_string();
    assert!(e.contains("nope") && e.contains("dep"), "{e}");
    assert_ne!(lock_of(&f).entries["dep"].commit, up.head());

    deps::update(&f.root, &m, Some("dep"), &mut diags).unwrap();
    assert_eq!(lock_of(&f).entries["dep"].commit, up.head());
}

#[test]
fn changed_rev_in_manifest_repins() {
    need_git!();
    let up = Upstream::new();
    let f = consumer(&up.url(), "master");
    f.load().unwrap();
    assert_eq!(checkout_head(&f), up.head());

    f.write("project.toml", &manifest(&up.url(), "v1"));
    let p = f.load().unwrap();
    assert_eq!(lock_of(&f).entries["dep"].rev, "v1");
    assert_eq!(lock_of(&f).entries["dep"].commit, up.first);
    assert_eq!(checkout_head(&f), up.first);
    assert!(
        infos(&p).iter().any(|m| m.starts_with("pinned dep v1 -> ")),
        "{:?}",
        infos(&p)
    );
}

#[test]
fn tag_resolves_to_peeled_commit() {
    need_git!();
    let up = Upstream::new();
    let tag_object = git_in(&up.repo(), &["rev-parse", "v1"]);
    assert_ne!(tag_object, up.first, "the fixture tag must be annotated");
    let root = tempfile::tempdir().unwrap();
    let r = root.path();
    assert_eq!(resolve_rev(r, "dep", &up.url(), "v1").unwrap(), up.first);
    assert_eq!(
        resolve_rev(r, "dep", &up.url(), "master").unwrap(),
        up.head()
    );
}

#[test]
fn full_and_short_hashes_resolve() {
    need_git!();
    let up = Upstream::new();
    let root = tempfile::tempdir().unwrap();
    let r = root.path();
    // A full hash needs no network at all: any url works.
    let full = up.first.clone();
    assert_eq!(
        resolve_rev(r, "dep", "/does/not/exist", &full).unwrap(),
        full
    );
    // A short hash is resolved through the dependency's own checkout.
    for len in [7, 9, 12] {
        let short = &full[..len];
        assert_eq!(resolve_rev(r, "dep", &up.url(), short).unwrap(), full);
    }
    assert!(r.join("build/deps/dep/source/.git").exists());
    let e = resolve_rev(r, "dep", &up.url(), "no-such-ref").unwrap_err();
    assert!(e.contains("no-such-ref") && e.contains(&up.url()), "{e}");
}

fn scratch_dirs() -> usize {
    fs::read_dir(std::env::temp_dir())
        .unwrap()
        .filter_map(Result::ok)
        .filter(|e| e.file_name().to_string_lossy().starts_with("forge-rev-"))
        .count()
}

#[test]
fn abbreviated_rev_is_locked_as_full_sha_without_scratch_clone() {
    need_git!();
    let up = Upstream::new();
    let before = scratch_dirs();
    let f = consumer(&up.url(), &up.first[..10]);
    f.load().unwrap();
    assert_eq!(lock_of(&f).entries["dep"].commit, up.first);
    assert_eq!(lock_of(&f).entries["dep"].commit.len(), 40);
    assert_eq!(lock_of(&f).entries["dep"].rev, up.first[..10]);
    assert_eq!(checkout_head(&f), up.first);
    assert_eq!(scratch_dirs(), before);

    // update leaves a clone in the checkout directory, never a scratch one.
    let m = config::load(&f.manifest()).unwrap();
    deps::update(&f.root, &m, None, &mut Diagnostics::default()).unwrap();
    assert_eq!(scratch_dirs(), before);
}

#[test]
fn removed_dependency_is_pruned_from_lock() {
    need_git!();
    let up = Upstream::new();
    let two = with_other(&up, "deps = [\"dep\", \"other\"]");
    let f = Fixture::new(&two);
    f.touch("main.c");
    f.load().unwrap();
    assert_eq!(
        lock_of(&f).entries.keys().collect::<Vec<_>>(),
        ["dep", "other"]
    );

    f.write("project.toml", &manifest(&up.url(), "master"));
    f.load().unwrap();
    assert_eq!(lock_of(&f).entries.keys().collect::<Vec<_>>(), ["dep"]);
}

/// The manifest with a second git dependency `other`; `app_deps` is the
/// `deps` line of the bin.
fn with_other(up: &Upstream, app_deps: &str) -> String {
    format!(
        concat!(
            "[workspace]\nname = \"t\"\nversion = \"1\"\nc = \"17\"\n",
            "[dependency.dep]\ngit = \"{url}\"\nrev = \"master\"\nkind = \"header-only\"\n",
            "include.public = [\"include\"]\n",
            "[dependency.other]\ngit = \"{url}\"\nrev = \"v1\"\nkind = \"header-only\"\n",
            "[bin.app]\nsources = [\"main.c\"]\n{deps}\n",
        ),
        url = up.url(),
        deps = app_deps
    )
}

#[test]
fn an_unused_git_dependency_is_not_fetched_but_keeps_its_lock_entry() {
    need_git!();
    let up = Upstream::new();
    let f = Fixture::new(&with_other(&up, "deps = [\"dep\", \"other\"]"));
    f.touch("main.c");
    f.load().unwrap();
    let locked = lock_of(&f).entries["other"].clone();
    assert!(f.root.join("build/deps/other").exists());

    // `other` is no longer used: no checkout is touched, the pin stays.
    fs::remove_dir_all(f.root.join("build/deps/other")).unwrap();
    f.write("project.toml", &with_other(&up, "deps = [\"dep\"]"));
    let p = f.load().unwrap();
    assert!(!f.root.join("build/deps/other").exists());
    assert_eq!(lock_of(&f).entries["other"], locked);
    assert!(
        infos(&p)
            .iter()
            .any(|m| m.starts_with("dependency other is not used on ")),
        "{:?}",
        p.diagnostics
    );
}

#[test]
fn checkout_is_offline_when_already_at_commit() {
    need_git!();
    let up = Upstream::new();
    let f = consumer(&up.url(), "master");
    f.load().unwrap();
    let pinned = up.head();

    // The upstream disappears; the locked checkout is all that is needed.
    let moved = up.dir.path().join("moved");
    fs::rename(up.repo(), &moved).unwrap();
    let p = f.load().unwrap();
    assert_eq!(checkout_head(&f), pinned);
    assert!(infos(&p).iter().all(|m| !m.starts_with("pinned")));
}

#[test]
fn damaged_checkout_is_repaired() {
    need_git!();
    let up = Upstream::new();
    let f = consumer(&up.url(), "master");
    f.load().unwrap();
    let src = f.root.join("build/deps/dep/source");
    fs::remove_dir_all(src.join(".git")).unwrap();
    f.load().unwrap();
    assert_eq!(checkout_head(&f), up.head());
}

#[test]
fn checkout_returns_the_deterministic_directory() {
    need_git!();
    let up = Upstream::new();
    let root = tempfile::tempdir().unwrap();
    let dir = checkout(root.path(), "dep", &up.url(), &up.first).unwrap();
    assert_eq!(dir, root.path().join("build/deps/dep/source"));
    assert_eq!(git_in(&dir, &["rev-parse", "HEAD"]), up.first);
    assert!(dir.join("include/dep.h").is_file());
}

#[test]
fn unreachable_url_names_the_dependency() {
    need_git!();
    let up = Upstream::new();
    let missing = up
        .dir
        .path()
        .join("missing")
        .to_string_lossy()
        .replace('\\', "/");
    let f = consumer(&missing, "master");
    let e = f.error();
    assert!(e.contains("dependency.dep") && e.contains(&missing), "{e}");
}

#[test]
fn path_dependencies_are_not_locked() {
    let f = Fixture::new(
        "[workspace]\nname = \"t\"\nversion = \"1\"\nc = \"17\"\n[dependency.stb]\npath = \"vendor/stb\"\nkind = \"header-only\"\ninclude.public = [\".\"]\n[bin.app]\nsources = [\"main.c\"]\ndeps = [\"stb\"]\n",
    );
    f.touch("main.c");
    f.touch("vendor/stb/stb.h");
    f.load().unwrap();
    assert!(!f.root.join("project.lock").exists());
}
